const { readFileSync } = require('node:fs')
const { resolve, join } = require('node:path')
const assert = require('node:assert/strict')
const root = resolve(__dirname, '../dist/worker')
const text = readFileSync(join(root, 'index.js'), 'utf8')
for (const marker of ['node:', 'from "electron"', 'require(', 'process.env', 'synthetic-worker', 'test/fixtures', '__vite-browser-external']) assert.ok(!text.includes(marker), `Worker bundle contains ${marker}`)
const inputs = JSON.parse(readFileSync(join(root, 'BUILD-INPUTS.json'), 'utf8')).inputs
assert.ok(inputs.every(name => !name.includes('node_modules/')))
const example = readFileSync(join(root, 'worker.example.jsonc'), 'utf8')
assert.match(example, /"WEB_ENABLED":\s*"0"/)
assert.match(example, /"workers_dev":\s*false/)
assert.match(example, /"preview_urls":\s*false/)
assert.ok(!/"account_id"|"routes"|"ASR_API_KEY"\s*:|"TRANSLATION_API_KEY"\s*:/.test(example))
assert.ok(readFileSync(join(root, 'LICENSE')).length && readFileSync(join(root, 'NOTICE.md')).length)
console.log('Worker bundle inspected: default denied, fixed upstreams, no credentials/test fixture/Node runtime; actual Workers runtime and deployment remain unverified.')
